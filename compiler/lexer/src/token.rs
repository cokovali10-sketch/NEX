use nex_diagnostics::Span;

/// Lexical tokens of NEX 0.1 plus reserved keywords for planned features.
#[derive(Debug, Clone, PartialEq)]
pub enum TokenKind {
    Ident(String),
    Int(i64),
    Float(f64),
    Str(String),
    Char(char),

    Fn,
    Let,
    Var,
    Const,
    If,
    Elif,
    Else,
    While,
    For,
    In,
    Return,
    Break,
    Continue,
    Struct,
    Enum,
    Impl,
    Trait,
    Import,
    From,
    As,
    Pub,
    Async,
    Await,
    True,
    False,
    None,
    And,
    Or,
    Not,
    Match,
    Extern,
    Unsafe,
    Type,
    Module,
    Use,

    LParen,
    RParen,
    LBracket,
    RBracket,
    LBrace,
    RBrace,
    Comma,
    Colon,
    Semicolon,
    Dot,
    DotDot,
    DotDotDot,
    Question,
    Arrow,

    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    PlusEq,
    MinusEq,
    StarEq,
    SlashEq,
    PercentEq,
    Eq,
    EqEq,
    Bang,
    BangEq,
    Lt,
    LtEq,
    Gt,
    GtEq,
    Amp,
    AmpAmp,
    Pipe,
    PipePipe,
    Caret,
    Tilde,
    Shl,
    Shr,

    Newline,
    Indent,
    Dedent,
    Eof,
}

impl TokenKind {
    pub fn describe(&self) -> String {
        match self {
            Self::Ident(name) => format!("identifier `{name}`"),
            Self::Int(value) => format!("integer `{value}`"),
            Self::Float(value) => format!("float `{value}`"),
            Self::Str(_) => "string literal".to_string(),
            Self::Char(_) => "character literal".to_string(),
            Self::Newline => "newline".to_string(),
            Self::Indent => "indent".to_string(),
            Self::Dedent => "dedent".to_string(),
            Self::Eof => "end of file".to_string(),
            other => format!("`{}`", other.symbol()),
        }
    }

    pub fn symbol(&self) -> &'static str {
        match self {
            Self::Fn => "fn",
            Self::Let => "let",
            Self::Var => "var",
            Self::Const => "const",
            Self::If => "if",
            Self::Elif => "elif",
            Self::Else => "else",
            Self::While => "while",
            Self::For => "for",
            Self::In => "in",
            Self::Return => "return",
            Self::Break => "break",
            Self::Continue => "continue",
            Self::Struct => "struct",
            Self::Enum => "enum",
            Self::Impl => "impl",
            Self::Trait => "trait",
            Self::Import => "import",
            Self::From => "from",
            Self::As => "as",
            Self::Pub => "pub",
            Self::Async => "async",
            Self::Await => "await",
            Self::True => "true",
            Self::False => "false",
            Self::None => "none",
            Self::And => "and",
            Self::Or => "or",
            Self::Not => "not",
            Self::Match => "match",
            Self::Extern => "extern",
            Self::Unsafe => "unsafe",
            Self::Type => "type",
            Self::Module => "module",
            Self::Use => "use",
            Self::LParen => "(",
            Self::RParen => ")",
            Self::LBracket => "[",
            Self::RBracket => "]",
            Self::LBrace => "{",
            Self::RBrace => "}",
            Self::Comma => ",",
            Self::Colon => ":",
            Self::Semicolon => ";",
            Self::Dot => ".",
            Self::DotDot => "..",
            Self::DotDotDot => "...",
            Self::Question => "?",
            Self::Arrow => "->",
            Self::Plus => "+",
            Self::Minus => "-",
            Self::Star => "*",
            Self::Slash => "/",
            Self::Percent => "%",
            Self::PlusEq => "+=",
            Self::MinusEq => "-=",
            Self::StarEq => "*=",
            Self::SlashEq => "/=",
            Self::PercentEq => "%=",
            Self::Eq => "=",
            Self::EqEq => "==",
            Self::Bang => "!",
            Self::BangEq => "!=",
            Self::Lt => "<",
            Self::LtEq => "<=",
            Self::Gt => ">",
            Self::GtEq => ">=",
            Self::Amp => "&",
            Self::AmpAmp => "&&",
            Self::Pipe => "|",
            Self::PipePipe => "||",
            Self::Caret => "^",
            Self::Tilde => "~",
            Self::Shl => "<<",
            Self::Shr => ">>",
            Self::Ident(_) | Self::Int(_) | Self::Float(_) | Self::Str(_) | Self::Char(_) => "",
            Self::Newline => "\\n",
            Self::Indent => "<indent>",
            Self::Dedent => "<dedent>",
            Self::Eof => "<eof>",
        }
    }
}

#[derive(Debug, Clone, PartialEq)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
}

impl Token {
    pub fn new(kind: TokenKind, span: Span) -> Self {
        Self { kind, span }
    }
}
